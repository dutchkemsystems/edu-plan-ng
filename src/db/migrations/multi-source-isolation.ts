export async function runMultiSourceIsolationMigration(client: Client): Promise<void> {
  console.log('[Migration] Starting Multi-Source Registry & NDPA 2023 isolation migration...');

  // 1. Create curriculum_sources table
  await client.execute(`
    CREATE TABLE IF NOT EXISTS curriculum_sources (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      code TEXT NOT NULL UNIQUE,
      authority TEXT NOT NULL,
      default_jurisdiction TEXT NOT NULL,
      supported_classes TEXT NOT NULL,
      description TEXT,
      website_url TEXT,
      legal_notice TEXT NOT NULL,
      is_active INTEGER DEFAULT 1,
      created_at TEXT NOT NULL
    );
  `);

  // 2. Create source_curriculum table (Metadata-only transformative schema: NO raw copyrighted textbook text)
  await client.execute(`
    CREATE TABLE IF NOT EXISTS source_curriculum (
      id TEXT PRIMARY KEY,
      source_id TEXT NOT NULL,
      class_level TEXT NOT NULL,
      subject TEXT NOT NULL,
      version TEXT NOT NULL DEFAULT 'v1.0',
      topics TEXT NOT NULL, -- JSON array of transformative topic metadata
      objectives TEXT NOT NULL, -- JSON array of pedagogical Bloom verbs & objectives
      textbook_refs TEXT NOT NULL, -- JSON array of approved textbook metadata references
      statutory_citations TEXT,
      hash TEXT NOT NULL,
      updated_at TEXT NOT NULL,
      FOREIGN KEY (source_id) REFERENCES curriculum_sources(id)
    );
  `);

  // Create composite index for source curriculum lookup
  await client.execute(`
    CREATE INDEX IF NOT EXISTS idx_source_curriculum_composite
    ON source_curriculum (source_id, class_level, subject);
  `);

  // 3. Create school_source_preferences table
  await client.execute(`
    CREATE TABLE IF NOT EXISTS school_source_preferences (
      id TEXT PRIMARY KEY,
      school_id TEXT NOT NULL,
      class_level TEXT NOT NULL,
      subject TEXT NOT NULL,
      preferred_source_id TEXT NOT NULL,
      mandated_by_ministry INTEGER DEFAULT 0,
      updated_at TEXT NOT NULL,
      FOREIGN KEY (preferred_source_id) REFERENCES curriculum_sources(id)
    );
  `);

  await client.execute(`
    CREATE INDEX IF NOT EXISTS idx_school_source_pref
    ON school_source_preferences (school_id, class_level, subject);
  `);

  // 4. Create NDPA Tables: parental_consents, data_processing_logs, dpia_violations
  await client.execute(`
    CREATE TABLE IF NOT EXISTS parental_consents (
      id TEXT PRIMARY KEY,
      school_id TEXT NOT NULL,
      student_id TEXT NOT NULL,
      parent_name TEXT NOT NULL,
      parent_phone TEXT NOT NULL,
      parent_email TEXT,
      consent_granted INTEGER NOT NULL DEFAULT 0,
      consent_date TEXT,
      purpose TEXT NOT NULL,
      ip_address TEXT,
      user_agent TEXT,
      created_at TEXT NOT NULL
    );
  `);

  await client.execute(`
    CREATE TABLE IF NOT EXISTS data_processing_logs (
      id TEXT PRIMARY KEY,
      school_id TEXT NOT NULL,
      user_id TEXT NOT NULL,
      action TEXT NOT NULL,
      data_subject_category TEXT NOT NULL,
      contains_pii INTEGER DEFAULT 0,
      processing_purpose TEXT NOT NULL,
      legal_basis TEXT NOT NULL,
      dpo_reviewed INTEGER DEFAULT 0,
      timestamp TEXT NOT NULL
    );
  `);

  await client.execute(`
    CREATE TABLE IF NOT EXISTS dpia_violations (
      id TEXT PRIMARY KEY,
      school_id TEXT NOT NULL,
      user_id TEXT NOT NULL,
      violation_type TEXT NOT NULL,
      attempted_action TEXT NOT NULL,
      blocked INTEGER DEFAULT 1,
      details TEXT NOT NULL,
      severity TEXT DEFAULT 'HIGH',
      timestamp TEXT NOT NULL
    );
  `);

  // 5. Add state_id to schools if missing
  try {
    await client.execute(`ALTER TABLE schools ADD COLUMN state_id TEXT DEFAULT 'lagos';`);
    console.log('[Migration] Added state_id column to schools table.');
  } catch (e: any) {
    if (!String(e).includes('duplicate column')) {
      // Column already exists or table has it
    }
  }

  // 6. Add ministry_state_id to users if missing
  try {
    await client.execute(`ALTER TABLE users ADD COLUMN ministry_state_id TEXT DEFAULT 'lagos';`);
    console.log('[Migration] Added ministry_state_id column to users table.');
  } catch (e: any) {
    if (!String(e).includes('duplicate column')) {
      // Column already exists or table has it
    }
  }

  // 7. Seed the exact 6 curriculum sources
  const now = new Date().toISOString();
  for (const src of STATUTORY_CURRICULUM_SOURCES) {
    await client.execute({
      sql: `
        INSERT OR REPLACE INTO curriculum_sources (
          id, name, code, authority, default_jurisdiction, supported_classes,
          description, website_url, legal_notice, is_active, created_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?)
      `,
      args: [
        src.id,
        src.name,
        src.code,
        src.authority,
        src.defaultJurisdiction,
        src.supportedClasses,
        src.description,
        src.websiteUrl,
        src.legalNotice,
        now,
      ],
    });
  }

  console.log(`[Migration] Successfully seeded ${STATUTORY_CURRICULUM_SOURCES.length} curriculum sources.`);
}
