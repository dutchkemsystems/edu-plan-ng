interface SourceEntitlementData {
  tierId: string;
  tierName: string;
  allowedSourcesCount: number;
  sourceAccessSummary: string;
  activeSources: string[];
  sources: Array<{
    id: string;
    accessible: boolean;
    isActive: boolean;
    isStateRestricted?: boolean;
    stateRestrictionReason?: string | null;
    upgradeRequirement: string | null;
  }>;
}

interface CurriculumSourceSelectorProps {
  currentSourceId?: string;
  onSourceChange?: (sourceId: string, sourceMeta: CurriculumSourceOption) => void;
  compact?: boolean;
  tierKey?: string;
  onOpenPricing?: () => void;
}

export const CurriculumSourceSelector: React.FC<CurriculumSourceSelectorProps> = ({
  currentSourceId,
  onSourceChange,
  compact = false,
  tierKey,
  onOpenPricing,
}) => {
  const [selectedId, setSelectedId] = useState<string>(() => {
    if (currentSourceId) return currentSourceId;
    if (typeof localStorage !== 'undefined') {
      return localStorage.getItem('eduplan_curriculum_source') || 'lagos_scheme';
    }
    return 'lagos_scheme';
  });

  const [isOpen, setIsOpen] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);
  const [entitlements, setEntitlements] = useState<SourceEntitlementData | null>(null);
  const [upgradeModalSource, setUpgradeModalSource] = useState<CurriculumSourceOption | null>(null);

  useEffect(() => {
    fetchEntitlements();
  }, [tierKey]);

  const fetchEntitlements = async () => {
    try {
      const res = await fetch('/api/subscription/source-entitlements', {
        headers: getAuthHeaders(),
        credentials: 'include',
      });
      const data = await res.json();
      if (data && data.success) {
        setEntitlements(data);
      }
    } catch {
      // fallback
    }
  };

  useEffect(() => {
    if (currentSourceId && currentSourceId !== selectedId) {
      setSelectedId(currentSourceId);
    }
  }, [currentSourceId]);

  const activeOption =
    CURRICULUM_SOURCE_OPTIONS.find((s) => s.id === selectedId) || CURRICULUM_SOURCE_OPTIONS[0];

  const handleSelect = async (option: CurriculumSourceOption) => {
    // Check if source is restricted under statutory state policy
    const sourceEnt = entitlements?.sources?.find((s) => s.id === option.id);
    if (sourceEnt?.isStateRestricted) {
      setNotice(`Statutory Restriction: ${sourceEnt.stateRestrictionReason || 'Lagos State Ministry mandates the Lagos State Unified Scheme for public schools.'}`);
      setTimeout(() => setNotice(null), 8000);
      setIsOpen(false);
      return;
    }

    const isAccessible = sourceEnt ? sourceEnt.accessible : true;

    if (!isAccessible) {
      setUpgradeModalSource(option);
      setIsOpen(false);
      return;
    }

    // Persist choice to backend
    try {
      await fetch('/api/subscription/select-source', {
        method: 'POST',
        headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
        credentials: 'include',
        body: JSON.stringify({ sourceId: option.id }),
      });
    } catch {
      // optimistic update continues
    }

    setSelectedId(option.id);
    setIsOpen(false);
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('eduplan_curriculum_source', option.id);
    }

    // Show statutory legal notice on switch
    setNotice(option.legalNotice);

    if (onSourceChange) {
      onSourceChange(option.id, option);
    }

    // Refresh entitlements to update active source state
    fetchEntitlements();

    // Auto-dismiss notice after 6 seconds
    setTimeout(() => {
      setNotice(null);
    }, 6000);
  };

  return (
    <div className="relative inline-block text-left w-full sm:w-auto">
      {/* Selector Button */}
      <div className="flex items-center gap-2">
        <button
          type="button"
          onClick={() => setIsOpen(!isOpen)}
          className={`w-full sm:w-auto inline-flex items-center justify-between gap-3 px-3.5 py-2 rounded-xl text-xs font-semibold border transition-all ${
            compact
              ? 'bg-white hover:bg-slate-50 text-slate-800 border-slate-200 shadow-2xs'
              : 'bg-white hover:bg-slate-50 text-slate-900 border-slate-300 shadow-xs'
          }`}
          aria-haspopup="true"
          aria-expanded={isOpen}
        >
          <div className="flex items-center gap-2 text-left">
            <BookMarked className="w-4 h-4 text-emerald-700 shrink-0" />
            <div>
              <div className="flex items-center gap-1.5">
                <span className="text-[10px] uppercase font-bold text-slate-400 block tracking-wider leading-none">
                  Curriculum Source
                </span>
                {entitlements && (
                  <span className="text-[9px] font-bold px-1 rounded bg-slate-100 text-slate-600">
                    {entitlements.allowedSourcesCount === 6 ? 'All 6' : `${entitlements.allowedSourcesCount} Allowed`}
                  </span>
                )}
              </div>
              <span className="font-bold text-slate-800 truncate block max-w-[200px] sm:max-w-[240px]">
                {activeOption.name}
              </span>
            </div>
          </div>
          <ChevronDown className="w-3.5 h-3.5 text-slate-400 shrink-0 ml-1" />
        </button>

        <span className={`hidden md:inline-flex px-2 py-0.5 rounded text-[10px] font-bold border ${activeOption.badgeColor}`}>
          {activeOption.classScope}
        </span>
      </div>

      {/* Dropdown Menu */}
      {isOpen && (
        <>
          <div
            className="fixed inset-0 z-40"
            onClick={() => setIsOpen(false)}
          />
          <div className="absolute left-0 mt-2 w-80 sm:w-96 rounded-2xl bg-white shadow-2xl border border-slate-200 z-50 p-2 space-y-1 animate-in fade-in duration-150">
            <div className="px-3 py-2 border-b border-slate-100 flex items-center justify-between">
              <div>
                <h4 className="text-xs font-bold text-slate-900">Official Curriculum Authority</h4>
                <p className="text-[10px] text-slate-500">
                  {entitlements?.sourceAccessSummary || '6 statutory examination & syllabus registries'}
                </p>
              </div>
              <ShieldCheck className="w-4 h-4 text-emerald-600" />
            </div>

            <div className="max-h-[360px] overflow-y-auto space-y-1 py-1">
              {CURRICULUM_SOURCE_OPTIONS.map((opt) => {
                const isSelected = opt.id === selectedId;
                const sourceEnt = entitlements?.sources?.find((s) => s.id === opt.id);
                const isStateRestricted = sourceEnt?.isStateRestricted || false;
                const isAccessible = !isStateRestricted && (sourceEnt ? sourceEnt.accessible : true);

                return (
                  <button
                    key={opt.id}
                    onClick={() => handleSelect(opt)}
                    className={`w-full text-left p-2.5 rounded-xl transition-colors flex items-start gap-2.5 ${
                      isSelected
                        ? 'bg-emerald-50/80 border border-emerald-200'
                        : isStateRestricted
                        ? 'bg-rose-50/60 border border-rose-200/70 hover:bg-rose-50'
                        : !isAccessible
                        ? 'bg-slate-50/70 border border-slate-100 opacity-80 hover:bg-slate-100/70'
                        : 'hover:bg-slate-50 border border-transparent'
                    }`}
                  >
                    <div className="pt-0.5">
                      <div className={`w-4 h-4 rounded-full flex items-center justify-center border ${
                        isSelected
                          ? 'bg-emerald-700 border-emerald-700 text-white'
                          : isStateRestricted
                          ? 'border-rose-400 text-rose-700 bg-rose-100'
                          : !isAccessible
                          ? 'border-slate-300 text-slate-400 bg-slate-100'
                          : 'border-slate-300'
                      }`}>
                        {isSelected ? (
                          <Check className="w-3 h-3 stroke-[3]" />
                        ) : isStateRestricted ? (
                          <ShieldCheck className="w-2.5 h-2.5 text-rose-700" />
                        ) : !isAccessible ? (
                          <Lock className="w-2.5 h-2.5 text-slate-500" />
                        ) : null}
                      </div>
                    </div>
                    <div className="flex-1 min-w-0">
                      <div className="flex items-center justify-between gap-1">
                        <span className="text-xs font-bold text-slate-900 truncate">
                          {opt.name}
                        </span>
                        {isStateRestricted ? (
                          <span className="text-[9px] font-bold px-1.5 py-0.5 rounded bg-rose-100 text-rose-800 border border-rose-200 shrink-0 flex items-center gap-1">
                            <ShieldCheck className="w-2.5 h-2.5" />
                            <span>State Mandate</span>
                          </span>
                        ) : !isAccessible ? (
                          <span className="text-[9px] font-bold px-1.5 py-0.5 rounded bg-amber-100 text-amber-900 shrink-0 flex items-center gap-1">
                            <Lock className="w-2.5 h-2.5" />
                            <span>Upgrade</span>
                          </span>
                        ) : (
                          <span className={`text-[9px] font-bold px-1.5 py-0.2 rounded border ${opt.badgeColor} shrink-0`}>
                            {opt.classScope}
                          </span>
                        )}
                      </div>
                      <p className="text-[10px] text-slate-500 mt-0.5 leading-snug">
                        {opt.authority}
                      </p>
                      {isStateRestricted && sourceEnt?.stateRestrictionReason && (
                        <p className="text-[9px] font-medium text-rose-800 mt-0.5">
                          {sourceEnt.stateRestrictionReason}
                        </p>
                      )}
                      {!isAccessible && !isStateRestricted && sourceEnt?.upgradeRequirement && (
                        <p className="text-[9px] font-semibold text-amber-800 mt-0.5">
                          {sourceEnt.upgradeRequirement}
                        </p>
                      )}
                    </div>
                  </button>
                );
              })}
            </div>

            <div className="p-2.5 rounded-xl bg-slate-50 border border-slate-100 text-[10px] text-slate-500 flex items-start gap-2">
              <Info className="w-3.5 h-3.5 text-slate-400 shrink-0 mt-0.5" />
              <span>
                EduPlan NG is compliant with Section 20 of the Nigerian Copyright Act 2022 (Transformative Educational Fair Dealing).
              </span>
            </div>
          </div>
        </>
      )}

      {/* Upgrade Modal for Locked Source */}
      {upgradeModalSource && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-xs p-4 animate-in fade-in duration-150">
          <div className="bg-white rounded-3xl max-w-md w-full border border-slate-200 shadow-2xl p-6 space-y-4">
            <div className="flex items-start justify-between pb-3 border-b border-slate-100">
              <div className="flex items-center gap-2">
                <div className="p-2 bg-amber-100 text-amber-800 rounded-xl">
                  <Lock className="w-5 h-5 text-amber-700" />
                </div>
                <div>
                  <h3 className="text-base font-black text-slate-900">
                    Source Upgrade Required
                  </h3>
                  <span className="text-xs text-slate-500">Phase 4 Source Allocation Gate</span>
                </div>
              </div>
              <button
                onClick={() => setUpgradeModalSource(null)}
                className="p-1.5 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-100"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <div className="bg-amber-50/80 rounded-2xl p-4 border border-amber-200/90 space-y-2">
              <p className="text-xs text-amber-950 font-semibold leading-relaxed">
                Your current tier (<strong>{entitlements?.tierName || 'Active Plan'}</strong>) allows{' '}
                <strong>{entitlements?.allowedSourcesCount || 1} curriculum source(s)</strong>.
              </p>
              <p className="text-xs text-amber-900 leading-relaxed">
                To unlock <strong className="text-amber-950">{upgradeModalSource.name}</strong>, choose an upgraded plan:
              </p>
              <ul className="text-xs text-amber-950 space-y-1 list-disc list-inside font-medium pt-1">
                <li><strong>B2C Pro Termly / Session (₦1,500–₦3,000):</strong> 2 sources + Exam Gen, Report Cards &amp; Parent Comms</li>
                <li><strong>B2B Silver (₦120,000/term):</strong> 2 sources, 40 teachers + Exams, Timetable AI, SEN, Parent Portal</li>
                <li><strong>B2B Gold (₦250,000/term) / B2G Platinum:</strong> All 6 sources + Heatmap, Fee Recovery, 3D/4K, White-Label &amp; LMS</li>
              </ul>
            </div>

            <div className="flex items-center justify-end gap-2 pt-2">
              <button
                type="button"
                onClick={() => setUpgradeModalSource(null)}
                className="px-4 py-2 bg-slate-100 hover:bg-slate-200 text-slate-800 text-xs font-bold rounded-xl transition-colors"
              >
                Keep Current Source
              </button>
              <button
                type="button"
                onClick={() => {
                  setUpgradeModalSource(null);
                  if (onOpenPricing) {
                    onOpenPricing();
                  } else {
                    window.location.hash = '#/pricing';
                  }
                }}
                className="px-4 py-2 bg-amber-600 hover:bg-amber-500 text-white text-xs font-bold rounded-xl transition-colors shadow-sm flex items-center gap-1.5"
              >
                <span>View Upgrade Plans</span>
                <ArrowRight className="w-3.5 h-3.5" />
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Statutory Legal Notice Toast on Switch */}
      {notice && (
        <div className="fixed bottom-6 right-6 z-50 max-w-md bg-slate-900 text-white p-4 rounded-2xl shadow-2xl border border-slate-700 flex items-start gap-3 animate-in slide-in-from-bottom-3 duration-200">
          <ShieldCheck className="w-5 h-5 text-emerald-400 shrink-0 mt-0.5" />
          <div className="flex-1">
            <h5 className="text-xs font-bold text-emerald-300">Statutory Source Switched</h5>
            <p className="text-xs text-slate-200 mt-1 leading-relaxed">
              {notice}
            </p>
          </div>
          <button
            onClick={() => setNotice(null)}
            className="text-slate-400 hover:text-white text-xs font-bold p-1 rounded-lg hover:bg-slate-800"
          >
            ✕
          </button>
        </div>
      )}
    </div>
  );
};
